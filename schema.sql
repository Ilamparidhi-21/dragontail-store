CREATE TABLE IF NOT EXISTS dt_products (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 category VARCHAR(30) NOT NULL CHECK (category IN ('Women','Men','Accessories')),
 type VARCHAR(80) NOT NULL,
 price INTEGER NOT NULL CHECK (price BETWEEN 0 AND 10000000),
 image TEXT NOT NULL,
 alt_image TEXT NOT NULL,
 tag VARCHAR(50) NOT NULL DEFAULT '',
 colors TEXT[] NOT NULL DEFAULT '{}',
 sizes TEXT[] NOT NULL DEFAULT '{}',
 description TEXT NOT NULL DEFAULT '',
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_dt_products_active_category ON dt_products(active,category);
